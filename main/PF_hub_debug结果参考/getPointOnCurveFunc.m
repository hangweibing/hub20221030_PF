function [x,y,COMPLEX_SOULTION] = getPointOnCurveFunc(point1,point2,center,r,location)
% =========================================================================
% getPointOnCurveFunc - 计算直线与圆弧的交点
%
% 功能描述:
%   该函数计算由两点确定的直线与指定圆心的圆的交点，并根据方向参数选择合适的交点。
%   用于裂纹扩展路径与几何边界（圆角）的交点计算。
%
% 输入参数:
%   point1  - 直线上的第一个点 [x1, y1]
%   point2  - 直线上的第二个点 [x2, y2]
%   center  - 圆心坐标 [a, b]
%   r       - 圆半径
%   location- 选择交点的方向，可选值: 'left'(左侧) 或 'right'(右侧)
%
% 输出参数:
%   x               - 所选交点的x坐标
%   y               - 所选交点的y坐标
%   COMPLEX_SOULTION- 是否存在复数解的标志 (true/false)
%
% 数学原理:
%   圆方程: (x-a)^2 + (y-b)^2 = r^2
%   直线方程: c*x + d*y = e
%   联立方程求解得到两个交点，选择距离合适的一个
%
% 注意事项:
%   - 当直线与圆没有交点时，返回复数解
%   - 'left'/'right'是相对于直线方向从point1到point2的定义
% =========================================================================
% ============ 参数提取和初始化 ============
% 圆心坐标
a = center(1);
b = center(2);

% 初始化标志
COMPLEX_SOULTION = false;

% 直线两点坐标
x1 = point1(1);
y1 = point1(2);
x2 = point2(1);
y2 = point2(2);

% ============ 直线方程参数计算 ============
% 直线方程: c*x + d*y = e
c = y2 - y1;        % y方向差值
d = x1 - x2;        % x方向差值
e = x1*y2 - x2*y1;  % 常数项
% ============ 直线与圆的交点计算 ============
% 通过联立圆方程和直线方程求解，得到两个交点：
% 交点1: (xc1, yc1) - 距离直线起点较近的交点
% 交点2: (xc2, yc2) - 距离直线起点较远的交点

% 交点1坐标 (离线段起点较近)
xc1 = (1/2).*(c.^2+d.^2).^(-1).*((-2).*b.*c.*d+2.*a.*d.^2+2.*c.*e+ ...
       (-1).*((2.*b.*c.*d+(-2).*a.*d.^2+(-2).*c.*e).^2+(-4).*(c.^2+ ...
       d.^2).*(a.^2.*d.^2+b.^2.*d.^2+(-2).*b.*d.*e+e.^2+(-1).* ...
       d.^2.*r.^2)).^(1/2));

yc1 = -(d.^(-1).*((-1).*b.*c.^2.*d.*(c.^2+d.^2).^(-1)+a.*c.*d.^2.*( ...
       c.^2+d.^2).^(-1)+(-1).*e+c.^2.*(c.^2+d.^2).^(-1).*e+(-1/2).* ...
       c.*(c.^2+d.^2).^(-1).*((2.*b.*c.*d+(-2).*a.*d.^2+(-2).*c.*e) ...
       .^2+(-4).*(c.^2+d.^2).*(a.^2.*d.^2+b.^2.*d.^2+(-2).*b.*d.*e+ ...
       e.^2+(-1).*d.^2.*r.^2)).^(1/2)));

% 交点2坐标 (远离线段起点)
xc2 = (1/2).*(c.^2+d.^2).^(-1).*((-2).*b.*c.*d+2.*a.*d.^2+2.*c.*e+ ...
       ((2.*b.*c.*d+(-2).*a.*d.^2+(-2).*c.*e).^2+(-4).*(c.^2+d.^2) ...
       .*(a.^2.*d.^2+b.^2.*d.^2+(-2).*b.*d.*e+e.^2+(-1).*d.^2.* ...
       r.^2)).^(1/2));

yc2 = (-1).*d.^(-1).*((-1).*b.*c.^2.*d.*(c.^2+d.^2).^(-1)+a.*c.* ...
       d.^2.*(c.^2+d.^2).^(-1)+(-1).*e+c.^2.*(c.^2+d.^2).^(-1).*e+( ...
       1/2).*c.*(c.^2+d.^2).^(-1).*((2.*b.*c.*d+(-2).*a.*d.^2+(-2) ...
       .*c.*e).^2+(-4).*(c.^2+d.^2).*(a.^2.*d.^2+b.^2.*d.^2+(-2).* ...
       b.*d.*e+e.^2+(-1).*d.^2.*r.^2)).^(1/2));
% ============ 根据方向选择合适的交点 ============
% 根据location参数选择左侧或右侧的交点
% 选择逻辑基于x坐标的大小关系

if strcmp(location, 'left')
    % 选择左侧交点（x坐标较小的一个）
    if xc1 < xc2
        x = xc1;
        y = yc1;
    else
        x = xc2;
        y = yc2;
    end

elseif strcmp(location, 'right')
    % 选择右侧交点（x坐标较大的一个）
    if xc1 < xc2
        x = xc2;
        y = yc2;
    else
        x = xc1;
        y = yc1;
    end

else
    % 参数错误处理
    error('方向定义错误，仅可使用''left''和''right''')
end
% ============ 复数解检测 ============
% 检查计算结果是否为复数（表示直线与圆没有实数交点）
if ~isreal(x) || ~isreal(y)
    COMPLEX_SOULTION = true;
end
end
