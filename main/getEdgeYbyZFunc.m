% =========================================================================
% getEdgeYbyZFunc - 根据Z坐标和位置计算对应的Y坐标边界值
%
% 描述:
%   该函数根据给定的Z坐标和位置参数('up'或'down')，计算几何形状边界上的Y坐标值。
%   主要用于处理包含圆弧过渡区域的几何边界计算。
%
% 输入参数:
%   z        - Z坐标值 (标量或数组)
%   location - 位置参数，可选值: 'up'(上边界) 或 'down'(下边界)
%   y_in     - (可选) 当前的Y坐标值，用于点(z,y)圆心连线和圆弧的交点计算
%
% 输出参数:
%   y - 对应的Y坐标边界值
%   z - 对应的Z坐标边界值 (在圆弧段由于投影方式改变可能发生变化)
%
% 注意:
%   - 当z <= 35时，返回固定边界值
%   - 当35 < z <= 37.82842712时，计算圆弧上的点（根据连线方向投影）
%   - 当z > 37.82842712时，返回另一固定边界值
% =========================================================================
function [y, z] = getEdgeYbyZFunc(z, location, y_in)

    % 如果没有提供y_in，则默认为空，后续按原垂直投影处理
    if nargin < 3
        y_in = [];
    end

    % 根据位置参数处理不同的边界计算
    if strcmp(location, 'up')
        % 上边界计算逻辑
        % 直线区域: z <= 35
        if z <= 35
            y = 13;
        end

        % 圆弧过渡区域: 35 < z <= 37.82842712
        % 圆心坐标 (37.82842712, 14)，半径为3
        if z > 35 && z <= 37.82842712
            if ~isempty(y_in)
                % 计算点（z,y_in）圆心连线和圆弧的交点
                zc = 37.82842712;
                yc = 14;
                r = 3;
                dz = z - zc;
                dy = y_in - yc;
                dist = sqrt(dz.^2 + dy.^2);
                % 按连线方向投影到圆周上
                y = yc + r * dy ./ (dist + eps);
                z = zc + r * dz ./ (dist + eps);
            else
                % 原有的垂直投影计算方式
                y = 14 - sqrt(9 - (z - 37.82842712).^2);
            end
        end

        % 直线区域: z > 37.82842712
        if z > 37.82842712
            y = 11;
        end

    elseif strcmp(location, 'down')
        % 下边界计算逻辑
        if z <= 35
            y = 7;
        end

        % 圆弧过渡区域: 35 < z <= 37.82842712
        % 圆心坐标 (37.82842712, 6)，半径为3
        if z > 35 && z <= 37.82842712
            if ~isempty(y_in)
                % 计算点（z,y_in）圆心连线和圆弧的交点
                zc = 37.82842712;
                yc = 6;
                r = 3;
                dz = z - zc;
                dy = y_in - yc;
                dist = sqrt(dz.^2 + dy.^2);
                % 按连线方向投影到圆周上
                y = yc + r * dy ./ (dist + eps);
                z = zc + r * dz ./ (dist + eps);
            else
                % 原有的垂直投影计算方式
                y = sqrt(9 - (z - 37.82842712).^2) + 6;
            end
        end

        % 直线区域: z > 37.82842712
        if z > 37.82842712
            y = 9;
        end

        % 边界情况处理：如果y变量未定义，设置默认值
        if ~exist('y', 'var')
            y = 7;
        end

    end

end

