%% ===================================================================
%% 函数名称：getModelIndexFunc
%% 功能描述：根据上下表面裂纹长度确定裂纹发展阶段模型索引
%% ===================================================================
function [curModelIndex] = getModelIndexFunc(a_up, a_down)
%GETMODELINDEXFUNC 根据上下表面裂纹长度确定裂纹发展阶段
%
% 输入参数：
%   a_up:          上表面裂纹长度 (mm)
%   a_down:        下表面裂纹长度 (mm)
%
% 输出参数：
%   curModelIndex: 裂纹发展阶段索引 (0-7,12)
%                  0: 无效状态，需要重新采样
%                  1-7: 对应的神经网络模型阶段
%                  12: 特殊初始状态
%
% 阶段划分依据：
%   - 基于裂纹长度范围划分不同的发展阶段
%   - 每个阶段对应不同的几何形状和扩展模式
%   - 使用预训练的神经网络模型进行预测
%% 阶段判断逻辑
% 注意：优先级从高到低，第一个满足条件的即为结果

%% 阶段12：微小裂纹（近似无裂纹）-> 上边界
% 物理意义：裂纹极小，可视为初始无损状态
if(a_up <= 1e-7 && a_up > 0)
    curModelIndex = 12;

%% 阶段1：小裂纹（半圆形）-> 上边界
% 物理意义：上表面存在小裂纹，下表面无明显损伤
% 几何特征：近似半圆形裂纹，主要向上表面扩展
elseif(a_up <= 5 && a_up > 1e-7)
    curModelIndex = 1;

%% 阶段2：圆形裂纹 -> 上边界
% 物理意义：裂纹已发展到圆形阶段，下表面仍有保护层
% 几何特征：近似圆形，下表面几乎未受损 (a_down ≤ 0.01)
elseif(a_up > 5 && a_up < 7.82842712 && a_down <= 1e-2)
    curModelIndex = 2;

%% 阶段3：圆形裂纹 -> 下边界
% 物理意义：上下表面都开始出现损伤，但仍处于圆形阶段
% 几何特征：圆形裂纹向上下两个方向扩展
elseif(a_up >= 5 && a_up < 7.82842712 && 1e-2 < a_down && a_down < 5)
    curModelIndex = 3;

%% 阶段4：圆形-椭圆过渡
% 物理意义：裂纹从圆形向椭圆过渡的临界阶段
% 几何特征：上下表面裂纹长度相近，都接近几何边界
% 长度范围定义：
%   - 上边界7.82842712mm = 初始圆心z=30到下表面圆角圆心z=37.82842712的距离
%   - 下边界5mm = 经验阈值，表示裂纹开始显著影响几何形状
%   - 该范围确保裂纹在几何约束内进行圆形到椭圆的自然过渡
elseif(a_up >= 5 && a_up < 7.828427122 && a_down > 5 && a_down < 7.82842712)
    curModelIndex = 4;

%% 阶段5：椭圆形 -> 下边界
% 物理意义：裂纹已发展为椭圆形，主要向下表面扩展
% 几何特征：上表面裂纹较大，下表面相对较小 (a_down < 5)
elseif(a_up > 7.82842712 && a_down < 5)
    curModelIndex = 5;

%% 阶段6：椭圆形 -> 圆形过渡
% 物理意义：椭圆形裂纹向穿透过渡阶段
% 几何特征：上下表面都较大，但还未完全穿透
elseif(a_up > 7.82842712 && a_down > 5 && a_down < 7.82842712)
    curModelIndex = 6;

%% 阶段7：完全穿透阶段
% 物理意义：裂纹已完全穿透工件，进入最终扩展阶段
% 几何特征：上下表面都已穿透，裂纹呈长条形
elseif(a_up > 7.82842712 && a_up < 55 && a_down > 7.82842712 && a_down < 55)
    curModelIndex = 7;

%% 无效状态：需要重新采样
% 物理意义：裂纹长度超出合理范围或处于未定义区域
else
    curModelIndex = 0;  % 返回0表示需要重新采样粒子
end

