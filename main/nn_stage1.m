%% 输入数据归一化函数
% 将原始输入数据映射到[-1, 1]范围
function y = mapminmax_apply(x, settings)
    y = bsxfun(@minus, x, settings.xoffset);  % 减去偏移量
    y = bsxfun(@times, y, settings.gain);     % 乘以缩放系数
    y = bsxfun(@plus, y, settings.ymin);      % 加上最小值偏移
end

%% 双曲正切激活函数
% 实现对称S型激活函数：tansig(n) = 2/(1+exp(-2n)) - 1
function a = tansig_apply(n, ~)
    a = 2 ./ (1 + exp(-2 * n)) - 1;
end

%% 输出数据反归一化函数
% 将网络输出映射回原始物理值范围
function x = mapminmax_reverse(y, settings)
    x = bsxfun(@minus, y, settings.ymin);     % 减去最小值偏移
    x = bsxfun(@rdivide, x, settings.gain);   % 除以缩放系数
    x = bsxfun(@plus, x, settings.xoffset);   % 加上偏移量
end
