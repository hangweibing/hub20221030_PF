% 核采样函数：使用拒绝采样方法从目标分布中生成样本
% 输入参数：
%   N - 需要的样本数量
% 输出参数：
%   e - 生成的样本数组，大小为1xN
function [e] = kernelsampling(N)
    % 初始化样本数组，大小为1xN
    e = zeros(1, N); % 初始化存储样本的数组
    n = 0; % 当前已接受的样本数量
    % 定义目标分布函数：f(t) = 0.75*(1-t.^2)
    f = @(t) 0.75*(1-t.^2);

    while n < N
        % 在[-1,1]范围内生成候选样本点
        t = rand(1)*2-1; % 生成范围在[-1,1]之间的随机数
        % 计算目标分布在t点处的函数值
        f1 = f(t);
        % 生成[0,1]范围内的均匀随机数用于接受-拒绝判断
        r = rand(1);  % 生成范围在[0,1]之间的随机数
        % 如果随机数r小于等于目标分布函数值f(t)，则接受这个样本
        if r <= f1     % 接受条件：r <= f(t)，此时接受候选点t作为样本
            n = n + 1; % 已接受样本数量加1
            e(n) = t;  % 将接受的样本存储到数组中
        end
    end
end

